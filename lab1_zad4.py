import math

# Вводим два неотрицательных числа с клавиатуры
a: float = float(input("Введите первое число (a): "))
b: float = float(input("Введите второе число (b): "))

# Вычисляем среднее арифметическое и среднее геометрическое
arith_mean: float = (a + b) / 2
geom_mean: float = math.sqrt(a * b)

# Выводим результаты с пояснениями
print(f"Среднее арифметическое чисел {a} и {b}: {arith_mean:.2f}")
print(f"Среднее геометрическое чисел {a} и {b}: {geom_mean:.2f}")
